-- ============ HASH (djb2) ============
local function _hc_hash(str)
    local h = 5381
    for i = 1, #str do
        h = (h * 33 + string.byte(str, i)) % 2147483647
    end
    return tostring(math.floor(h))
end

-- ============ DEVICE SERIAL ============
local function _hc_getDeviceId()
    local id = nil
    pcall(function()
        local KSL = import("KismetSystemLibrary")
        if KSL then
            if KSL.GetDeviceId then id = KSL.GetDeviceId() end
            if (not id or id == "") and KSL.GetDeviceIdOS then id = KSL.GetDeviceIdOS() end
        end
    end)
    if id then id = tostring(id):gsub("[^A-Za-z0-9%-_]", "") end
