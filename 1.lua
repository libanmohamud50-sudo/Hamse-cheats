local function _hc_mapReason(reason)
    if not reason then return "nonet" end
    if reason == "USER BLOCKED" then return "blocked" end
    if reason == "EXPIRED KEY" then return "expired" end
    if reason == "MAX DEVICE REACHED" then return "device_limit" end
    if reason == "USER OR GAME NOT REGISTERED" then return "invalid" end
    return "nonet"
end

-- ============ LICENSE CHECK ============
local function _hc_checkLicense(key, serial, callback)
    local httpMgr = nil
    pcall(function()
        httpMgr = ModuleManager.GetModule(ModuleManager.CommonModuleConfig.http_manager)
    end)
    if not httpMgr or not httpMgr.Post then
        callback(false, "nonet", nil); return
    end
    local headers = { ["Content-Type"] = "application/x-www-form-urlencoded" }
    local body = "game=" .. _HC_CONFIG.GAME_NAME .. "&user_key=" .. key .. "&serial=" .. serial
    httpMgr:Post(_HC_CONFIG.LOGIN_URL, headers, body, nil, function(ok, response)
        if ok and response then
            if response:find("\"status\"%s*:%s*true") and response:find("\"data\"%s*:") then
                callback(true); return
            end
            local reason = nil
            pcall(function()
                if response then reason = response:match("\"reason\"%s*:%s*\"([^\"]+)\"") end
            end)
            callback(false, _hc_mapReason(reason), nil)
        else
            callback(false, "nonet", nil)
        end
    end, 15)
end

