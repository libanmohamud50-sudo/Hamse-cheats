                        _G._HC_LICENSE_UID = serial
                        _hc_setStatus("Key OK... Loading...", false)
                        if onSuccess then onSuccess() end
                    else
                        if reason == "invalid"      then _hc_setStatus("Wrong Key", true)
                        elseif reason == "blocked"  then _hc_setStatus("Key Blocked", true)
                        elseif reason == "expired"  then _hc_setStatus("Key Expired", true)
                        elseif reason == "device_limit" then _hc_setStatus("Key locked to another device", true)
                        else _hc_setStatus("Connection error - try again", true) end
                    end
                end)
            end)

        -- footer
        _hc_makeText(root, _HC_CONFIG.SUPPORT_TEXT,
            math.floor(13 * sc), LC(0.0, 0.7, 0.9, 1.0),
            cx, cy + panelH * 0.33, 9993)

        _G._HC_LOGIN_UI = root

        -- ======== ANIMATION TIMER ========
        -- Uses AddGameTimer (fastest available tick ~50ms) to drive:
        --   1. Fade-in: dim + panel alpha 0->1 over ~0.6s
        --   2. Scan bar: horizontal bounce sweep across panel
        --   3. Top/bottom glow lines: pulse brightness
        local _animSc = sc
        local _animPW = panelW
        local _animPH = panelH
        local _animCX = cx
        local _animCY = cy
        local _animT  = 0
        local _scanPos = 0
        local _scanDir = 1

        if character and slua.isValid(character.Object) then
            local animTimer = character:AddGameTimer(50, true, function()
                if not slua.isValid(root) then return end
                _animT = _animT + 0.05  -- 50ms step

                -- 1. Fade in dim (0 -> 0.82 over 0.5s)
                local dimAlpha = math.min(1, _animT / 0.5) * 0.82
                pcall(function()
                    if _G._HC_DIM_WIDGET and slua.isValid(_G._HC_DIM_WIDGET) then
                        _G._HC_DIM_WIDGET:SetBrushColor(LC(0, 0, 0, dimAlpha))
                    end
                end)

                -- 2. Scan bar bounce (left-right sweep)
                local scanRange = _animPW - 24 * _animSc
                _scanPos = _scanPos + _scanDir * (scanRange / 60)
                if _scanPos >= scanRange then _scanPos = scanRange; _scanDir = -1 end
                if _scanPos <= 0        then _scanPos = 0;          _scanDir =  1 end
                local scanAlpha = 0.12 + (math.sin(_animT * 2.5) + 1) * 0.5 * 0.18
                pcall(function()
                    if _G._HC_SCAN_BAR and slua.isValid(_G._HC_SCAN_BAR) then
                        local slot = _G._HC_SCAN_BAR:GetSlot()
                        if slot then
                            slot:SetPosition(V2(
                                _animCX - _animPW * 0.5 + 10 * _animSc + _scanPos,
                                _animCY - _animPH * 0.17))
                        end
                        _G._HC_SCAN_BAR:SetBrushColor(LC(0.0, 0.9, 1.0, scanAlpha))
                    end
                end)

                -- 3. Glow lines pulse
                local pulse = (math.sin(_animT * 3.0) + 1) * 0.5
                local glowA = 0.6 + pulse * 0.4
                pcall(function()
                    if _G._HC_GLOW_TOP and slua.isValid(_G._HC_GLOW_TOP) then
                        _G._HC_GLOW_TOP:SetBrushColor(LC(0.0, 0.85, 1.0, glowA))
                    end
                    if _G._HC_GLOW_BOT and slua.isValid(_G._HC_GLOW_BOT) then
                        _G._HC_GLOW_BOT:SetBrushColor(LC(0.0, 0.85, 1.0, glowA))
                    end
                end)
            end)
            _G._HC_ANIM_TIMER  = animTimer
            _G._HC_LOGIN_CHAR  = character
            _G._HC_LOGIN_TIMER = animTimer
        end

        ok = true
    end)
    return ok
end

